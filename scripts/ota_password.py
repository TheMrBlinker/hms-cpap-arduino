# PlatformIO pre-script: enable /update only when a real password is configured.
#
# Sources (first non-empty wins):
#   1. environment variable OTA_PASSWORD
#        OTA_PASSWORD='...' pio run
#   2. untracked platformio_local.ini (listed in .gitignore), pulled in through
#      [platformio] extra_configs:
#        [ota]
#        password = ...
#
# The secret is NOT passed as a -D flag (it would show up in `pio run -v`
# output and in compile_commands.json). Instead it is written to
# $BUILD_DIR/ota_secret/ota_secret.h (inside .pio/, git-ignored) and only
# -DHAVE_OTA_SECRET is defined.
#
# No, an invalid or a placeholder password -> no header, no define -> /update
# is NOT registered (fail closed).
# Allowed: 8..64 chars from [A-Za-z0-9] and . _ ~ @ % + = , : ^ - ! * ( ) [ ] { } / ? # & ; < > |
# (printable ASCII without space, quotes, backtick, backslash and $).
# Characters such as ; or # may be cut off by the .ini parser: prefer the
# environment variable for those.
Import("env")  # noqa: F821
import os
import re

ALLOWED = re.compile(r"[A-Za-z0-9._~@%+=,:^\-!*()\[\]{}/?#&;<>|]{8,64}")
PLACEHOLDERS = {"change-me-please", "changeme", "change-me", "password",
                "yourpass", "your-password", "12345678", "admin123", "secret"}

build_dir = env.subst("$BUILD_DIR")  # noqa: F821
hdr_dir = os.path.join(build_dir, "ota_secret")
hdr_path = os.path.join(hdr_dir, "ota_secret.h")


def disable(msg):
    if os.path.exists(hdr_path):
        os.remove(hdr_path)
    print("*** OTA: %s -> /update endpoint DISABLED" % msg)


pw = os.environ.get("OTA_PASSWORD", "").strip()
source = "environment variable OTA_PASSWORD"
if not pw:
    try:
        pw = env.GetProjectConfig().get("ota", "password", "").strip()  # noqa: F821
    except Exception:
        pw = ""
    source = "[ota] password in platformio_local.ini"

if not pw:
    disable("no password configured")
elif not ALLOWED.fullmatch(pw):
    disable("password from %s rejected (need 8-64 chars, no space, quotes, "
            "backtick, backslash or $)" % source)
elif pw.lower() in PLACEHOLDERS or re.search(r"change.?me", pw, re.I):
    disable("placeholder password from %s rejected" % source)
else:
    # C string literal; escape '?' too (trigraphs) although -std=gnu++ ignores them.
    lit = pw.replace("?", "\\?")
    content = ("// GENERATED by scripts/ota_password.py - do not commit\n"
               "#pragma once\n#define OTA_PASSWORD \"%s\"\n" % lit)
    os.makedirs(hdr_dir, exist_ok=True)
    old = None
    if os.path.exists(hdr_path):
        with open(hdr_path) as f:
            old = f.read()
    if old != content:  # unchanged header -> no needless rebuild
        with open(hdr_path, "w") as f:
            f.write(content)
    env.Append(CPPPATH=[hdr_dir], CPPDEFINES=["HAVE_OTA_SECRET"])  # noqa: F821
    print("*** OTA: /update enabled (user admin, password from %s)" % source)
